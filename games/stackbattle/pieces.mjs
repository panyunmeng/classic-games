/**
 * 方块对战 · 方块几何与 SRS 数据（纯数据 + 纯函数，无 DOM / 无随机 / 无时钟）
 *
 * 为什么单独一层（必要性）：
 * 1. 逻辑层要判碰撞、AI 要推演落点、渲染要画预览，三方都需要「某块某旋转态占哪几格」。
 *    复制三份形态表必然漂移（改一处忘两处），所以只留这一份事实来源。
 * 2. 碰撞与自由下落在数学上只是「格子坐标 + 盘面占用」，与游戏规则无关；
 *    AI 复用同一份判定，等价于「AI 看到的世界 == 逻辑判定的世界」，
 *    不会出现 AI 认为放得下、逻辑判碰撞的偏差。
 *
 * 坐标约定：盘面 COLS×ROWS，y 向下为正；方块矩阵原点在其左上角，
 * 形态用矩阵内相对格 [cx, cy] 表示，落盘坐标 = 方块坐标 + 相对格。
 */

export const COLS = 10;
export const ROWS = 20;

/** 七种方块的四个旋转态，格坐标是各自矩阵内的 [x, y]（y 向下）。 */
export const PIECES = {
  I: [
    [[0, 1], [1, 1], [2, 1], [3, 1]],
    [[2, 0], [2, 1], [2, 2], [2, 3]],
    [[0, 2], [1, 2], [2, 2], [3, 2]],
    [[1, 0], [1, 1], [1, 2], [1, 3]],
  ],
  O: [
    [[1, 0], [2, 0], [1, 1], [2, 1]],
    [[1, 0], [2, 0], [1, 1], [2, 1]],
    [[1, 0], [2, 0], [1, 1], [2, 1]],
    [[1, 0], [2, 0], [1, 1], [2, 1]],
  ],
  T: [
    [[1, 0], [0, 1], [1, 1], [2, 1]],
    [[1, 0], [1, 1], [2, 1], [1, 2]],
    [[0, 1], [1, 1], [2, 1], [1, 2]],
    [[1, 0], [0, 1], [1, 1], [1, 2]],
  ],
  S: [
    [[1, 0], [2, 0], [0, 1], [1, 1]],
    [[1, 0], [1, 1], [2, 1], [2, 2]],
    [[1, 1], [2, 1], [0, 2], [1, 2]],
    [[1, 0], [0, 1], [1, 1], [0, 2]],
  ],
  Z: [
    [[0, 0], [1, 0], [1, 1], [2, 1]],
    [[2, 0], [1, 1], [2, 1], [1, 2]],
    [[0, 1], [1, 1], [1, 2], [2, 2]],
    [[1, 0], [0, 1], [1, 1], [2, 2]],
  ],
  J: [
    [[0, 0], [0, 1], [1, 1], [2, 1]],
    [[1, 0], [2, 0], [1, 1], [1, 2]],
    [[0, 1], [1, 1], [2, 1], [2, 2]],
    [[1, 0], [1, 1], [0, 2], [1, 2]],
  ],
  L: [
    [[2, 0], [0, 1], [1, 1], [2, 1]],
    [[1, 0], [1, 1], [1, 2], [2, 2]],
    [[0, 1], [1, 1], [2, 1], [0, 2]],
    [[0, 0], [1, 0], [1, 1], [1, 2]],
  ],
};

export const TYPES = ['I', 'O', 'T', 'S', 'Z', 'J', 'L'];

/**
 * SRS 踢墙表：来自 Tetris Wiki 的标准表，y 轴已按本实现「向下为正」取反。
 * 键是 "起态>终态"，值是依次尝试的 [dx, dy] 偏移，第一项永远是原地。
 */
const KICKS_JLSTZ = {
  '0>1': [[0, 0], [-1, 0], [-1, -1], [0, 2], [-1, 2]],
  '1>0': [[0, 0], [1, 0], [1, 1], [0, -2], [1, -2]],
  '1>2': [[0, 0], [1, 0], [1, 1], [0, -2], [1, -2]],
  '2>1': [[0, 0], [-1, 0], [-1, -1], [0, 2], [-1, 2]],
  '2>3': [[0, 0], [1, 0], [1, -1], [0, 2], [1, 2]],
  '3>2': [[0, 0], [-1, 0], [-1, 1], [0, -2], [-1, -2]],
  '3>0': [[0, 0], [-1, 0], [-1, 1], [0, -2], [-1, -2]],
  '0>3': [[0, 0], [1, 0], [1, -1], [0, 2], [1, 2]],
};
const KICKS_I = {
  '0>1': [[0, 0], [-2, 0], [1, 0], [-2, 1], [1, -2]],
  '1>0': [[0, 0], [2, 0], [-1, 0], [2, -1], [-1, 2]],
  '1>2': [[0, 0], [-1, 0], [2, 0], [-1, -2], [2, 1]],
  '2>1': [[0, 0], [1, 0], [-2, 0], [1, 2], [-2, -1]],
  '2>3': [[0, 0], [2, 0], [-1, 0], [2, -1], [-1, 2]],
  '3>2': [[0, 0], [-2, 0], [1, 0], [-2, 1], [1, -2]],
  '3>0': [[0, 0], [1, 0], [-2, 0], [1, 2], [-2, -1]],
  '0>3': [[0, 0], [-1, 0], [2, 0], [-1, -2], [2, 1]],
};

/** 方块矩阵边长：I 与 O 用 4×4，其余用 3×3（与 SRS 的生成位置一致）。 */
export function matrixSize(type) {
  return type === 'T' || type === 'S' || type === 'Z' || type === 'J' || type === 'L' ? 3 : 4;
}

/** 生成列：让矩阵在 10 列里居中；I 落在 3～6 列、O 落在 4～5 列，与标准一致。 */
export function spawnX(type) {
  return Math.floor((COLS - matrixSize(type)) / 2);
}

/** 方块的绝对格坐标列表（含可能落在盘面上方的负 y）。 */
export function cellsOf(piece) {
  const { type, rot, x, y } = piece;
  return PIECES[type][rot].map(([cx, cy]) => ({ x: x + cx, y: y + cy }));
}

/** 旋转 from→to 的踢墙候选（第一项为原地）。 */
export function rotateKicks(type, from, to) {
  if (type === 'O') return [[0, 0]];
  const table = type === 'I' ? KICKS_I : KICKS_JLSTZ;
  return table[`${from}>${to}`] || [[0, 0]];
}

/**
 * 碰撞判定：越左右墙、越过底线、与已落格重叠都算非法。
 * y < 0（盘面上方）允许，这样方块可以从顶部以外的地方生成/踢墙。
 */
export function blocked(grid, type, rot, x, y) {
  const cells = PIECES[type][rot];
  for (let i = 0; i < cells.length; i++) {
    const bx = x + cells[i][0];
    const by = y + cells[i][1];
    if (bx < 0 || bx >= COLS || by >= ROWS) return true;
    if (by >= 0 && grid[by][bx]) return true;
  }
  return false;
}

/**
 * 从 from 行自由下落到不能再落，返回落定行；当前就放不下则返回 null。
 * 逻辑的硬降与 AI 的落点推演都用它，保证两边的「落点」定义一致。
 */
export function dropY(grid, type, rot, x, from = 0) {
  if (blocked(grid, type, rot, x, from)) return null;
  let y = from;
  while (!blocked(grid, type, rot, x, y + 1)) y += 1;
  return y;
}
